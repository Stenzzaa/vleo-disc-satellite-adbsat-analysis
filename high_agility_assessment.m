%% ================================================================
%  OPTIONAL DYNAMIC-AGILITY ASSESSMENT
%  ================================================================

% ADBSat gives disturbance loads but NOT slew capability.
%
% To make a true high-agility pass/fail assessment, fill in actual or
% defensible spacecraft mass-property and actuator values below.
%
% Leave values as NaN until supported by the spacecraft design or
% literature/manufacturer data.

Ixx_kgm2 = NaN;
Iyy_kgm2 = NaN;
Izz_kgm2 = NaN;

