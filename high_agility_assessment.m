Ty_available_Nm = NaN;
Tz_available_Nm = NaN;

Hx_capacity_Nms = NaN;
Hy_capacity_Nms = NaN;
Hz_capacity_Nms = NaN;

% Representative manoeuvres for characterisation.
%
% These are NOT automatically requirements.
% Replace them if your supervisor specifies a particular slew requirement.

slew_angles_deg = [ ...
    30 ...
    45 ...
    60 ...
    90];

slew_times_s = [ ...
    10 ...
    20 ...
    30 ...
    60];

%% Kinematic requirements independent of inertia

nSlew = ...
    numel(slew_angles_deg) * ...
    numel(slew_times_s);

SlewAngle_deg = ...
    zeros(nSlew,1);

SlewTime_s = ...
    zeros(nSlew,1);

RequiredAngularAcceleration_rad_s2 = ...
    zeros(nSlew,1);

PeakAngularRate_deg_s = ...
    zeros(nSlew,1);

row = 0;

for i = 1:numel(slew_angles_deg)

    theta_rad = ...
        deg2rad( ...
        slew_angles_deg(i));

    for j = 1:numel(slew_times_s)

        row = row + 1;

        t = ...
            slew_times_s(j);

        % Symmetric bang-bang slew:
        %
        % accelerate for half the manoeuvre,
        % decelerate for half.
        %
        % theta = alpha*t^2/4
        %
        % therefore:
        %
        % alpha = 4*theta/t^2

        angular_accel = ...
            4 * theta_rad / ...
            t^2;

        omega_peak_rad_s = ...
            2 * theta_rad / ...
            t;

        SlewAngle_deg(row) = ...
            slew_angles_deg(i);

        SlewTime_s(row) = ...
            t;

        RequiredAngularAcceleration_rad_s2(row) = ...
            angular_accel;

        PeakAngularRate_deg_s(row) = ...
            rad2deg( ...
            omega_peak_rad_s);

    end

end

kinematic_agility = table( ...
    SlewAngle_deg, ...
    SlewTime_s, ...
    RequiredAngularAcceleration_rad_s2, ...
    PeakAngularRate_deg_s);

fprintf('\n');
