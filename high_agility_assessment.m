%% ================================================================
%  DISSERTATION FIGURE 4.6
%  Extended-attitude pitch behaviour
%  ================================================================

fig = figure( ...
    'Name','Extended-Attitude Aerodynamic Assessment', ...
    'Color','w', ...
    'Position',[100 100 1500 620]);

t = tiledlayout(fig,1,2, ...
    'TileSpacing','compact', ...
    'Padding','compact');

%% ================================================================
%  PANEL (a) - DIMENSIONAL DRAG
%  ================================================================

ax1 = nexttile(t,1);

hold(ax1,'on');
grid(ax1,'on');
box(ax1,'on');

plot( ...
    ax1, ...
    pitch_results.AoA_deg, ...
    pitch_results.Drag_N, ...
    '-o', ...
    'LineWidth',1.8, ...
    'MarkerSize',8);

% Operational pitch boundaries
xline(ax1,-30,'--k', ...
    'LineWidth',1.2, ...
    'HandleVisibility','off');

xline(ax1,+30,'--k', ...
    'LineWidth',1.2, ...
    'HandleVisibility','off');

xlabel(ax1,'AoA [deg]', ...
    'FontSize',16);

ylabel(ax1,'Drag [N]', ...
    'FontSize',16);

title(ax1,'(a) Extended-attitude drag', ...
    'FontSize',17, ...
    'FontWeight','bold');

xlim(ax1,[-95 95]);
xticks(ax1,-90:30:90);

set(ax1, ...
    'FontName','Times New Roman', ...
    'FontSize',14, ...
    'LineWidth',0.9, ...
    'Color','w', ...
    'XColor','k', ...
    'YColor','k', ...
    'GridColor',[0.72 0.72 0.72], ...
    'GridAlpha',0.40);

ax1.Toolbar.Visible = 'off';

%% ================================================================
%  PANEL (b) - TOTAL AERODYNAMIC MOMENT MAGNITUDE
%  ================================================================

ax2 = nexttile(t,2);

hold(ax2,'on');
grid(ax2,'on');
box(ax2,'on');

plot( ...
    ax2, ...
    pitch_results.AoA_deg, ...
    pitch_results.MomentMagnitude_Nm, ...
    '-o', ...
    'LineWidth',1.8, ...
    'MarkerSize',8);

% Operational pitch boundaries
xline(ax2,-30,'--k', ...
    'LineWidth',1.2, ...
    'HandleVisibility','off');

xline(ax2,+30,'--k', ...
    'LineWidth',1.2, ...
    'HandleVisibility','off');

xlabel(ax2,'AoA [deg]', ...
    'FontSize',16);

ylabel(ax2,'|M| [N m]', ...
    'FontSize',16);

title(ax2,'(b) Total aerodynamic moment magnitude', ...
    'FontSize',17, ...
    'FontWeight','bold');

xlim(ax2,[-95 95]);
xticks(ax2,-90:30:90);

set(ax2, ...
    'FontName','Times New Roman', ...
    'FontSize',14, ...
    'LineWidth',0.9, ...
    'Color','w', ...
    'XColor','k', ...
    'YColor','k', ...
    'GridColor',[0.72 0.72 0.72], ...
    'GridAlpha',0.40);

ax2.Toolbar.Visible = 'off';

