%% ================================================================
%  RUN ADBSat
%  ================================================================

for k = 1:nCase

    aoa = ...
        AoA_cases(k);

    aos = ...
        AoS_cases(k);

    fprintf( ...
        'Case %2d of %2d: AoA = %+6.1f deg, AoS = %+6.1f deg\n', ...
        k, ...
        nCase, ...
        aoa, ...
        aos);

    try

        out = run_adbsat_case( ...
            cfg_run, ...
            model_name, ...
            altitude_km, ...
            aoa, ...
            aos, ...
            gsi_model, ...
            override);

        %% Dynamic pressure

        q = ...
            0.5 * ...
            out.rho_kgm3 * ...
            out.vinf_ms^2;

        DynamicPressure_Pa(k) = ...
            q;

        %% Geometry

        AreaProj_m2(k) = ...
            out.AreaProj_m2;

        AreaRef_m2(k) = ...
            out.AreaRef_m2;

        %% Drag

        CD_ADBSat(k) = ...
            -out.Cf_w(1);

        CD_projected(k) = ...
            CD_ADBSat(k) * ...
            AreaRef_m2(k) / ...
            AreaProj_m2(k);

        Drag_N(k) = ...
            q * ...
            AreaRef_m2(k) * ...
            CD_ADBSat(k);

        %% Body-axis force coefficients

        CFx_B(k) = ...
            out.Cf_B(1);

        CFy_B(k) = ...
            out.Cf_B(2);

        CFz_B(k) = ...
            out.Cf_B(3);

        ForceCoefficientMagnitude(k) = ...
            norm(out.Cf_B);

        %% Body-axis moment coefficients

        CMx_B(k) = ...
            out.Cm_B(1);

        CMy_B(k) = ...
            out.Cm_B(2);

        CMz_B(k) = ...
            out.Cm_B(3);

        %% Dimensional moments

        Mx_Nm(k) = ...
            q * ...
            AreaRef_m2(k) * ...
            Lref_m * ...
            CMx_B(k);

        My_Nm(k) = ...
            q * ...
            AreaRef_m2(k) * ...
            Lref_m * ...
            CMy_B(k);

        Mz_Nm(k) = ...
            q * ...
            AreaRef_m2(k) * ...
            Lref_m * ...
            CMz_B(k);

        MomentMagnitude_Nm(k) = ...
            sqrt( ...
            Mx_Nm(k)^2 + ...
            My_Nm(k)^2 + ...
            Mz_Nm(k)^2);

        RunSuccessful(k) = true;

    catch ME

        warning( ...
            'Case AoA=%+.1f, AoS=%+.1f failed:\n%s', ...
            aoa, ...
            aos, ...
            ME.message);

        RunSuccessful(k) = false;

    end

end

