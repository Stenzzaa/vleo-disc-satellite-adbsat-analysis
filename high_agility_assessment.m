    0.5 * sum(S.meshdata.Areas);

%% ================================================================
%  ATTITUDE MATRIX
%  ================================================================

% Wide pure-pitch characterisation.
%
% This extends the established operational +/-30 deg range to +/-90 deg.

pitch_angles = [ ...
    -90 ...
    -75 ...
    -60 ...
    -45 ...
    -30 ...
    -20 ...
    -10 ...
      0 ...
     10 ...
     20 ...
     30 ...
     45 ...
     60 ...
     75 ...
     90];

% Wide pure-sideslip characterisation.

sideslip_angles = pitch_angles;

% Combined attitudes.
%
% We do not use +/-90 deg in the combined grid because the axis sweeps
% already characterise those extreme orientations and it avoids placing
% unnecessary emphasis on angular-coordinate edge cases.

combined_angles = [ ...
    -60 ...
    -30 ...
      0 ...
     30 ...
     60];

%% Construct case matrix

case_matrix = [];

% Pure pitch

for i = 1:numel(pitch_angles)

    case_matrix(end+1,:) = [ ...
        pitch_angles(i), ...
        0];

end

% Pure sideslip

for i = 1:numel(sideslip_angles)

    case_matrix(end+1,:) = [ ...
        0, ...
        sideslip_angles(i)];

end

% Combined AoA/AoS attitudes

for i = 1:numel(combined_angles)

    for j = 1:numel(combined_angles)

        case_matrix(end+1,:) = [ ...
            combined_angles(i), ...
            combined_angles(j)];

    end

end

%% Remove duplicate attitude pairs

case_matrix = ...
    unique( ...
    case_matrix, ...
    'rows', ...
    'stable');

AoA_cases = ...
    case_matrix(:,1);

AoS_cases = ...
    case_matrix(:,2);

nCase = ...
    size(case_matrix,1);

%% ================================================================
%  PREALLOCATE
%  ================================================================

