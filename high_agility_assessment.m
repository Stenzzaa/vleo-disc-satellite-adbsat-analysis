%% high_agility_assessment.m
% High-agility aerodynamic assessment for disc_lenticular_v03.
%
% PURPOSE
% -------
% Characterise the aerodynamic loading of the final spacecraft over a
% much wider attitude envelope than the nominal +/-30 deg imaging range.
%
% This study assesses AERODYNAMIC COMPATIBILITY with high agility.
%
% It does NOT by itself prove spacecraft slew performance.
% True agility additionally depends on:
% - spacecraft moments of inertia;
% - actuator torque;
% - actuator momentum storage;
% - required slew angle;
% - required slew time;
% - settling / pointing requirements.
%
% Final aerodynamic configuration:
% - disc_lenticular_v03
% - fine 8800-panel mesh
% - 300 km
% - Sentman alpha = 1
% - shadow ON
% - solar OFF
% - selected design CoM = [+6, 0, 0] mm
%
% The high-agility study contains:
%
% 1. Pure pitch sweep to +/-90 deg
% 2. Pure sideslip sweep to +/-90 deg
% 3. Combined AoA/AoS cases up to +/-60 deg
%
% Raw ADBSat results are saved in a dedicated subfolder to avoid
% overwriting the established final operational results.

if ~exist('cfg','var')
    project_config
end

