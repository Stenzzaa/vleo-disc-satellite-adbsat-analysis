%% Dynamic assessment only when inertias are supplied

if all(isfinite([ ...
        Ixx_kgm2 ...
        Iyy_kgm2 ...
        Izz_kgm2]))

    I_axes = [ ...
        Ixx_kgm2 ...
        Iyy_kgm2 ...
        Izz_kgm2];

    aero_disturbance = [ ...
        max_abs_Mx ...
        max_abs_My ...
        max_abs_Mz];

    fprintf('\n');
    fprintf('====================================================\n');
    fprintf('DYNAMIC SLEW TORQUE REQUIREMENTS\n');
    fprintf('====================================================\n');

    for axis = 1:3

        if axis == 1
            axis_name = 'X';
        elseif axis == 2
            axis_name = 'Y';
        else
            axis_name = 'Z';
        end

        fprintf('\n%s axis:\n', ...
            axis_name);

        for r = 1:height(kinematic_agility)

            alpha_req = ...
                kinematic_agility. ...
                RequiredAngularAcceleration_rad_s2(r);

            torque_inertial = ...
                I_axes(axis) * ...
                alpha_req;

            % Conservative addition of the maximum aerodynamic
            % disturbance opposing the commanded slew.

            torque_total = ...
                torque_inertial + ...
                aero_disturbance(axis);

            fprintf( ...
                '%3.0f deg in %4.0f s: ' + ...
                'inertial %.4e Nm, ' + ...
                'with aero %.4e Nm\n', ...
                kinematic_agility.SlewAngle_deg(r), ...
                kinematic_agility.SlewTime_s(r), ...
                torque_inertial, ...
                torque_total);

        end

    end

else

    fprintf('\n');
    fprintf('====================================================\n');
    fprintf('DYNAMIC AGILITY STATUS\n');
    fprintf('====================================================\n');

    fprintf(['No spacecraft inertias have been entered, therefore ' ...
        'a genuine slew-torque pass/fail assessment has NOT yet ' ...
        'been made.\n']);

    fprintf(['The aerodynamic envelope above is valid, but true ' ...
        'high-agility capability requires Ixx/Iyy/Izz and supported ' ...
        'actuator torque/momentum values.\n']);

end

